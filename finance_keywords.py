def detect_finance_jd(jd_text: str, job_title: str | None = None) -> bool:
    """JD 或岗位标题命中任一金融触发词即返回 True。"""
    haystack = (jd_text or "") + "\n" + (job_title or "")
    folded = haystack.casefold()
    return any(trigger.casefold() in folded for trigger in FINANCE_JD_TRIGGERS)


def finance_signals_in_resume(resume_text: str) -> list[str]:
    """返回简历中命中金融信号词的词（去重保序），供报告提示用。"""
    folded = (resume_text or "").casefold()
    return [word for word in dict.fromkeys(FINANCE_RESUME_SIGNALS) if word.casefold() in folded]


